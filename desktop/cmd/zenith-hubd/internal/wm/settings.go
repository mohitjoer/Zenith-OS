// genSettings renders settings.conf for an override set. follow is whether the
// window border tracks the live palette (borderFollowsPalette).
func genSettings(o Overrides, follow bool) string {
	var b strings.Builder
	b.WriteString(settingsHeader)

	if opts := diffOptions(o, follow); len(opts) > 0 {
		b.WriteString(opts.blocks())
		b.WriteString("\n")
	}
	if m := genMonitors(); m != "" {
		b.WriteString(m)
		b.WriteString("\n")
	}
	if a := genAnimations(o); a != "" {
		b.WriteString(a)
		b.WriteString("\n")
	}
	if g := genGesture(o); g != "" {
		b.WriteString(g)
		b.WriteString("\n")
	}

	var env strings.Builder
	// A cursor that diverges also exports the environment, so spawned apps see
	// the picked cursor: the start hook's setcursor reaches only the compositor
	// and XWayland.
	if d := defaultOverrides().Cursor; o.Cursor.Theme != d.Theme || o.Cursor.Size != d.Size {
		size := strconv.Itoa(o.Cursor.Size)
		fmt.Fprintf(&env, "env = XCURSOR_THEME,%s\n", hlStr(o.Cursor.Theme))
		fmt.Fprintf(&env, "env = XCURSOR_SIZE,%s\n", size)
		fmt.Fprintf(&env, "env = HYPRCURSOR_THEME,%s\n", hlStr(o.Cursor.Theme))
		fmt.Fprintf(&env, "env = HYPRCURSOR_SIZE,%s\n", size)
	}
	for _, e := range o.Env {
		if k := envKey(e.Key); k != "" {
			fmt.Fprintf(&env, "env = %s,%s\n", k, hlStr(e.Value))
		}
	}
	env.WriteString(genApps(o))
	if env.Len() > 0 {
		b.WriteString(env.String())
		b.WriteString("\n")
	}

	var rules strings.Builder
	rules.WriteString(genTameMaximizeOnOpen(o))
	for i, r := range o.WindowRules {
		rules.WriteString(genWindowRule(i, r))
	}
	for i, r := range o.LayerRules {
		rules.WriteString(genLayerRule(i, r))
	}
	for i, a := range o.AppOverrides {
		rules.WriteString(genAppOverride(i, a))
	}
	if rules.Len() > 0 {
		b.WriteString(rules.String())
	}

	var binds strings.Builder
	binds.WriteString(genUnbinds(o))
	for _, k := range o.Keybinds {
		binds.WriteString(genKeybind(k))
	}
	if binds.Len() > 0 {
		b.WriteString(binds.String())
		b.WriteString("\n")
	}

	if pl := genPlugins(o); pl != "" {
		b.WriteString(pl)
		b.WriteString("\n")
	}
	if start := genStartHook(o); start != "" {
		b.WriteString(start)
	}
	return b.String()
}

// envKey keeps an environment variable name to what `env =` can carry: a comma
// would end the name, and an empty or spaced one is no variable at all.
func envKey(k string) string {
	k = strings.TrimSpace(k)
	if k == "" || strings.ContainsAny(k, ", \t\r\n=#") {
		return ""
	}
	return k
}

// genApps exports env vars for the chosen browser and terminal so the CLI and
// xdg-open honour the same choice the keybinds launch. The editor keeps the
// packaged default (a terminal editor wants the bare binary), so it is set
// through the Environment page instead.
func genApps(o Overrides) string {
	var b strings.Builder
	if v := strings.TrimSpace(o.Apps["browser"]); v != "" {
		fmt.Fprintf(&b, "env = BROWSER,%s\n", hlStr(v))
	}
	if v := strings.TrimSpace(o.Apps["terminal"]); v != "" {
		fmt.Fprintf(&b, "env = TERMINAL,%s\n", hlStr(v))
	}
	return b.String()
}

