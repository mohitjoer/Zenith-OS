// dwindleForceSplit maps the friendly force-split labels onto Hyprland's
// dwindle:force_split integer (0 cursor, 1 left/top, 2 right/bottom).
func dwindleForceSplit(s string) int {
	switch s {
	case "left/top":
		return 1
	case "right/bottom":
		return 2
	default:
		return 0
	}
}

// --- rules ------------------------------------------------------------------

// windowRuleField maps the pretty boolean action keys onto Hyprland's rule
// names where they differ; a wrong name here makes the whole file fail to load.
var windowRuleField = map[string]string{
	"nodim": "no_dim", "noanim": "no_anim", "noblur": "no_blur",
	"noshadow": "no_shadow", "nofocus": "no_focus", "stayfocused": "stay_focused",
	"keepaspectratio": "keep_aspect_ratio",
}

// ruleBlock renders a named rule block. The block form is used rather than the
// one-line `windowrule = ..., match:...` so a regex containing a comma cannot be
// split into two fields.
func ruleBlock(kind, name string, match, props []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s {\n    name = %s\n", kind, name)
	for _, m := range match {
		fmt.Fprintf(&b, "    %s\n", m)
	}
	for _, p := range props {
		fmt.Fprintf(&b, "    %s\n", p)
	}
	b.WriteString("}\n")
	return b.String()
}

// genTameMaximizeOnOpen refuses the maximise request an app makes as it opens,
// for every window, so it lands as an ordinary tile inside the gaps rather than
// edge to edge. It rides Hyprland's own suppress_event, so a maximise the user
// asks for later still takes. Emitted before the user's own rules so a per-app
// rule can still win.
func genTameMaximizeOnOpen(o Overrides) string {
	if !o.Windows.TameMaximizeOnOpen {
		return ""
	}
	return ruleBlock("windowrule", "zenith-tame-maximize-on-open",
		[]string{"match:class = .*"}, []string{"suppress_event = maximize"})
}

func matchLines(class, title string) []string {
	var match []string
	if class != "" {
		match = append(match, "match:class = "+hlStr(class))
	}
	if title != "" {
		match = append(match, "match:title = "+hlStr(title))
	}
	return match
}

func genWindowRule(i int, r WindowRule) string {
	if r.Action == "" {
		return ""
	}
	match := matchLines(r.Class, r.Title)
	if len(match) == 0 {
		return ""
	}
	var prop string
	switch r.Action {
	case "float", "tile", "pin", "fullscreen", "maximize", "center", "immediate", "pseudo",
		"opaque", "xray", "nodim", "noanim", "noblur", "noshadow", "nofocus", "stayfocused",
		"keepaspectratio", "norounding", "noborder":
		field := windowRuleField[r.Action]
		switch r.Action {
		case "norounding":
			prop = "rounding = 0"
		case "noborder":
			prop = "border_size = 0"
		default:
			if field == "" {
				field = r.Action
			}
			prop = field + " = on"
		}
	case "opacity":
		prop = "opacity = " + hlNum(parseFloat(r.Value, 1))
	case "size":
		w, h := parseWxH(r.Value)
		prop = fmt.Sprintf("size = %d %d", w, h)
	case "move":
		x, y := parseWxH(r.Value)
		prop = fmt.Sprintf("move = %d %d", x, y)
	case "workspace":
		v := hlStr(r.Value)
		if v == "" {
			return ""
		}
		prop = "workspace = " + v
	case "idleinhibit":
		v := r.Value
		if v != "always" && v != "focus" && v != "fullscreen" {
			v = "always"
		}
		prop = "idle_inhibit = " + v
	case "suppressevent":
		v := r.Value
		if v != "maximize" && v != "fullscreen" && v != "activate" && v != "activatefocus" {
			v = "maximize"
		}
		prop = "suppress_event = " + v
	default:
		return ""
	}
	return ruleBlock("windowrule", fmt.Sprintf("zenith-user-%d", i+1), match, []string{prop})
}

func genLayerRule(i int, r LayerRule) string {
	if strings.TrimSpace(r.Namespace) == "" || r.Action == "" {
		return ""
	}
	var prop string
	switch r.Action {
	case "blur":
		prop = "blur = on"
	case "noanim":
		prop = "no_anim = on"
	case "blurpopups":
		prop = "blur_popups = on"
	case "xray":
		prop = "xray = on"
	case "abovelock":
		prop = "above_lock = on"
	case "noshadow":
		// A legacy action: layer surfaces no longer have a shadow effect. Drop it
		// rather than write a rule the compositor rejects.
		return ""
	case "ignorealpha":
		prop = "ignore_alpha = " + hlNum(parseFloat(r.Value, 0.5))
	case "dimaround":
		prop = "dim_around = on"
	default:
		return ""
	}
	return ruleBlock("layerrule", fmt.Sprintf("zenith-layer-%d", i+1),
		[]string{"match:namespace = " + hlStr(r.Namespace)}, []string{prop})
}

// genAppOverride renders one app's overrides as a single window rule: only the
// set fields become props. A numeric -1 and a toggle of "inherit" mean leave alone.
func genAppOverride(i int, a AppOverride) string {
	match := matchLines(a.Class, a.Title)
	if len(match) == 0 {
		return ""
	}
	var props []string
	if a.Opacity >= 0 && a.Opacity <= 1 {
		props = append(props, "opacity = "+hlNum(a.Opacity))
	}
	if a.Rounding >= 0 {
		props = append(props, fmt.Sprintf("rounding = %d", a.Rounding))
	}
	if a.BorderSize >= 0 {
		props = append(props, fmt.Sprintf("border_size = %d", a.BorderSize))
	}
	if a.Blur == "off" {
		props = append(props, "no_blur = on")
	}
	if a.Shadow == "off" {
		props = append(props, "no_shadow = on")
	}
	if a.Dim == "off" {
		props = append(props, "no_dim = on")
	}
	if a.Anim == "off" {
		props = append(props, "no_anim = on")
	}
	if a.Opaque == "on" {
		props = append(props, "opaque = on")
	}
	if len(props) == 0 {
		return ""
	}
	return ruleBlock("windowrule", fmt.Sprintf("zenith-app-%d", i+1), match, props)
}

// genStartHook runs the cursor setcursor and the user's autostart commands at
// session start. exec-once fires only for a fresh compositor, so a command
// added mid-session starts at the next login, the same as every other desktop's
// autostart.
func genStartHook(o Overrides) string {
	var lines []string
	d := defaultOverrides().Cursor
	if o.Cursor.Theme != d.Theme || o.Cursor.Size != d.Size {
		lines = append(lines, fmt.Sprintf("exec-once = hyprctl setcursor %s %d", hlStr(o.Cursor.Theme), o.Cursor.Size))
	}
	for _, a := range o.Autostart {
		if strings.TrimSpace(a.Command) == "" {
			continue
		}
		lines = append(lines, "exec-once = "+hlStr(a.Command))
	}
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

