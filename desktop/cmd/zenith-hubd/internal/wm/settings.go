//go:embed animpresets/*.conf
var animPresetFS embed.FS

// AnimPresets are the animation personalities the Hub offers. "zenith" is the
// packaged default and writes nothing.
var AnimPresets = []string{
	"zenith", "dusky", "bounce", "fade", "fast", "mechanical", "minimal", "rage",
	"slowmotion", "air", "hallucination", "exaggerated", "disable",
}

// IsAnimPreset reports whether name is one of the shipped presets.
func IsAnimPreset(name string) bool {
	for _, p := range AnimPresets {
		if p == name {
			return true
		}
	}
	return false
}

// AnimPresetPath is the plain file that holds the active preset's name.
func AnimPresetPath() string { return filepath.Join(zenithConfigDir(), "anim-preset") }

// CurrentAnimPreset reads the active preset, "zenith" when unset or unknown.
func CurrentAnimPreset() string {
	b, err := os.ReadFile(AnimPresetPath())
	if err != nil {
		return "zenith"
	}
	name := strings.TrimSpace(string(b))
	if !IsAnimPreset(name) {
		return "zenith"
	}
	return name
}

// presetLines is the preset's hyprlang body, empty for the default.
func presetLines(name string) string {
	if name == "" || name == "zenith" {
		return ""
	}
	b, err := animPresetFS.ReadFile("animpresets/" + name + ".conf")
	if err != nil {
		return ""
	}
	return string(b)
}

func baseCurves() string {
	b, _ := animPresetFS.ReadFile("animpresets/_base.conf")
	return string(b)
}

// genAnimItem renders one animation override line. Hyprland needs a curve on any
// enabled animation, so an item with none gets the built-in default.
func genAnimItem(it AnimItem) string {
	leaf := strings.TrimSpace(it.Leaf)
	if leaf == "" || strings.ContainsAny(leaf, ",\n") {
		return ""
	}
	if !it.Enabled {
		return fmt.Sprintf("animation = %s, 0\n", leaf)
	}
	curve := strings.TrimSpace(it.Bezier)
	if curve == "" {
		curve = "default"
	}
	parts := []string{leaf, "1", hlNum(it.Speed), hlStr(curve)}
	if it.Style != "" {
		parts = append(parts, hlStr(it.Style))
	}
	return "animation = " + strings.Join(parts, ", ") + "\n"
}

// genAnimBlock is the user's bezier curves (first, so items can reference them)
// then the per-leaf animation overrides.
func genAnimBlock(o Overrides) string {
	var b strings.Builder
	for _, c := range o.Anim.Curves {
		n := strings.TrimSpace(c.Name)
		if n == "" || strings.ContainsAny(n, ",\n") {
			continue
		}
		fmt.Fprintf(&b, "bezier = %s, %s, %s, %s, %s\n", n, hlNum(c.X0), hlNum(c.Y0), hlNum(c.X1), hlNum(c.Y1))
	}
	for _, it := range o.Anim.Items {
		b.WriteString(genAnimItem(it))
	}
	return b.String()
}

// genGesture is the workspace-swipe touchpad gesture when enabled.
func genGesture(o Overrides) string {
	if !o.Input.WorkspaceSwipe {
		return ""
	}
	n := o.Input.SwipeFingers
	if n < 3 {
		n = 3
	}
	return fmt.Sprintf("gesture = %d, horizontal, workspace\n", n)
}

// genMotion is the window-motion toggles the Look tab owns, kept out of the
// option diff so wobble can define its own curve. full restates the base feel
// too, so a preview can switch a toggle back off.
func genMotion(o Overrides, full bool) string {
	a := o.Appearance
	var b strings.Builder
	switch {
	case a.WobblyWindows:
		b.WriteString("animation = windowsMove, 1, 5, zenithWobble\n")
	case full:
		b.WriteString("animation = windowsMove, 1, 3.2, zenithSettle\n")
	}
	switch a.WindowStyle {
	case "slide", "gnomed":
		fmt.Fprintf(&b, "animation = windowsIn, 1, 3.8, zenithBloom, %s\n", a.WindowStyle)
		fmt.Fprintf(&b, "animation = windowsOut, 1, 2.4, zenithSettle, %s\n", a.WindowStyle)
	default:
		if full {
			b.WriteString("animation = windowsIn, 1, 3.8, zenithBloom, popin 78%\n")
			b.WriteString("animation = windowsOut, 1, 2.4, zenithSettle, popin 86%\n")
		}
	}
	return b.String()
}

// borderAngleHyprSpeed maps the friendly 1..10 rotation speed onto Hyprland's
// deciseconds-per-turn (higher is slower there), clamped so a stray value can't
// stall the sweep.
func borderAngleHyprSpeed(friendly float64) float64 {
	if friendly < 1 {
		friendly = 1
	}
	if friendly > 10 {
		friendly = 10
	}
	return 110 - friendly*10
}

// genAnimatedBorder is a rotating gradient on the active window border; off
// writes nothing to settings.conf (a preview stops the sweep, see
// genAnimatedBorderLive). The gradient needs two colours, so it uses the stored
// pair even when the border otherwise follows the palette.
func genAnimatedBorder(o Overrides) string {
	a := o.Appearance
	if !a.AnimatedBorder {
		return ""
	}
	d := defaultOverrides().Appearance
	var b strings.Builder
	fmt.Fprintf(&b, "general {\n    col.active_border = %s %s 45deg\n}\n",
		hlRGB(a.ActiveBorder, d.ActiveBorder), hlRGB(a.InactiveBorder, d.InactiveBorder))
	fmt.Fprintf(&b, "animation = borderangle, 1, %s, linear, loop\n", hlNum(borderAngleHyprSpeed(a.BorderAngleSpeed)))
	return b.String()
}

// genAnimations is every animation-related line of settings.conf: the base
// curves, the chosen preset, the motion toggles, the animated border and the
// user's own curves and per-leaf overrides, in that order so each layer wins
// over the one before.
func genAnimations(o Overrides) string {
	var b strings.Builder
	preset := presetLines(CurrentAnimPreset())
	motion := genMotion(o, false)
	needsBase := preset != "" || motion != "" || len(o.Anim.Curves) > 0 || len(o.Anim.Items) > 0 || o.Appearance.AnimatedBorder
	if !needsBase {
		return ""
	}
	b.WriteString(baseCurves())
	if preset != "" {
		b.WriteString("\n")
		b.WriteString(preset)
	}
	if motion != "" {
		b.WriteString("\n")
		b.WriteString(motion)
	}
	if ab := genAnimatedBorder(o); ab != "" {
		b.WriteString("\n")
		b.WriteString(ab)
	}
	if blk := genAnimBlock(o); blk != "" {
		b.WriteString("\n")
		b.WriteString(blk)
	}
	return b.String()
}

// --- live preview -----------------------------------------------------------

// previewCommands is the full-option preview as hyprctl batch commands, applied
// flash-free without touching a file: the options, the motion toggles, the
// animated border and the per-leaf animations, then the cursor. Rules, keybinds,
// env and autostart are not previewed; they apply on Save via reload.
func previewCommands(o Overrides) []string {
	follow := borderFollowsPalette(o)
	cmds := fullOptions(o, follow).keywords()
	cmds = append(cmds, keywordLines(genMotion(o, true))...)
	cmds = append(cmds, keywordLines(genAnimatedBorderLive(o))...)
	cmds = append(cmds, keywordLines(genAnimBlock(o))...)
	cmds = append(cmds, keywordLines(genPluginConfig(o))...)
	return cmds
}

// genAnimatedBorderLive is the border pieces a preview can push: the gradient
// when it is on, a stopped sweep when it is off. The active colour is an option,
// so it rides keyword rather than the file's block form.
func genAnimatedBorderLive(o Overrides) string {
	a := o.Appearance
	d := defaultOverrides().Appearance
	if !a.AnimatedBorder {
		return "animation = borderangle, 0\n"
	}
	return fmt.Sprintf("general:col.active_border = %s %s 45deg\nanimation = borderangle, 1, %s, linear, loop\n",
		hlRGB(a.ActiveBorder, d.ActiveBorder), hlRGB(a.InactiveBorder, d.InactiveBorder),
		hlNum(borderAngleHyprSpeed(a.BorderAngleSpeed)))
}

// keywordLines turns hyprlang `key = value` lines into `keyword key value`
// commands. Blank lines and comments are skipped.
func keywordLines(src string) []string {
	var out []string
	for _, line := range strings.Split(src, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key, val = strings.TrimSpace(key), strings.TrimSpace(val)
		switch key {
		case "animation", "bezier":
			out = append(out, "keyword "+key+" "+strings.ReplaceAll(val, ", ", ","))
		default:
			out = append(out, "keyword "+key+" "+val)
		}
	}
	return out
}

// --- scrolling layout -------------------------------------------------------

// scrollingOptions are the scrolling layout's knobs, emitted only when the layout
// is selected. The scrolling layout is a plugin on Hyprland 0.53, so its options
// live under plugin:hyprscrolling and exist only while the plugin is loaded.
func scrollingOptions(o Overrides) hlOpts {
	if o.Appearance.Layout != "scrolling" {
		return nil
	}
	var out hlOpts
	hs, dhs := o.Plugins.Hyprscrolling, defaultOverrides().Plugins.Hyprscrolling
	if hs.ColumnWidth != dhs.ColumnWidth {
		out.set("plugin:hyprscrolling:column_width", hs.ColumnWidth)
	}
	if hs.FollowFocus != dhs.FollowFocus {
		out.set("plugin:hyprscrolling:follow_focus", hs.FollowFocus)
	}
	return out
}

// sortedKeys returns a map's keys in order, for stable output.
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
