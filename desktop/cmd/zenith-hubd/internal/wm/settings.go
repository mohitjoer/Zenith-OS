// The settings.conf generator: appearance / input / cursor / animation leaves as
// diffs against the packaged defaults, window / layer / app rules, gestures,
// the start hook, and the full-option form the live preview pushes.
//
// Ported from Ryoku's settings.lua generator (GPL-3.0). The same decisions
// carry over (write only what diverges, so an untouched setting falls through
// to the packaged value); the output is hyprlang for Hyprland 0.53, where Ryoku
// wrote Lua for a newer one. Anything Hyprland 0.53 has no option for is not
// emitted and is reported by unhonored() instead of writing a line the
// compositor would reject, which would put an error banner on every login.

const settingsHeader = `# Generated by Zenith Settings (Super + ,). Do not edit this file: every change
# made in the Hub rewrites it. It is sourced after Zenith's defaults and before
# user.conf, so a line in user.conf still wins.

`

const rebindsHeader = `# Generated by Zenith Settings (the Keybinds page). Do not edit this file: every
# rebind made in the Hub rewrites it. A rebind is an unbind of the shipped chord
# followed by the same bind on the chord you chose.

`

// --- hyprlang rendering -----------------------------------------------------

// hlOpt is one Hyprland config option addressed by its colon path
// ("decoration:blur:size"). A list of them renders two ways: nested blocks for
// the file, and `keyword` calls for the live preview.
type hlOpt struct{ path, val string }

type hlOpts []hlOpt

func (o *hlOpts) set(path string, v any) { *o = append(*o, hlOpt{path, hlValue(v)}) }

// hlNode is a block while rendering: leaves and child blocks in the order they
// were added, so the output reads in the order the generator wrote it.
type hlNode struct {
	name  string
	items []hlItem
}

type hlItem struct {
	key, val string
	kid      *hlNode
}

func (n *hlNode) child(name string) *hlNode {
	for _, it := range n.items {
		if it.kid != nil && it.kid.name == name {
			return it.kid
		}
	}
	k := &hlNode{name: name}
	n.items = append(n.items, hlItem{kid: k})
	return k
}

func (n *hlNode) put(path []string, val string) {
	if len(path) == 1 {
		n.items = append(n.items, hlItem{key: path[0], val: val})
		return
	}
	n.child(path[0]).put(path[1:], val)
}

func (n *hlNode) render(b *strings.Builder, depth int) {
	pad := strings.Repeat("    ", depth)
	for _, it := range n.items {
		if it.kid == nil {
			fmt.Fprintf(b, "%s%s = %s\n", pad, it.key, it.val)
			continue
		}
		fmt.Fprintf(b, "%s%s {\n", pad, it.kid.name)
		it.kid.render(b, depth+1)
		fmt.Fprintf(b, "%s}\n", pad)
	}
}

// blocks renders the options as nested sections, one block per top-level name.
func (o hlOpts) blocks() string {
	root := &hlNode{}
	for _, opt := range o {
		root.put(strings.Split(opt.path, ":"), opt.val)
	}
	var b strings.Builder
	root.render(&b, 0)
	return b.String()
}

// keywords renders the options as the `keyword` calls hyprctl --batch takes.
func (o hlOpts) keywords() []string {
	out := make([]string, 0, len(o))
	for _, opt := range o {
		out = append(out, "keyword "+opt.path+" "+opt.val)
	}
	return out
}

// hlValue formats a value the way hyprlang reads it back.
func hlValue(v any) string {
	switch x := v.(type) {
	case bool:
		return strconv.FormatBool(x)
	case int:
		return strconv.Itoa(x)
	case float64:
		return hlNum(x)
	case string:
		return hlStr(x)
	}
	return hlStr(fmt.Sprint(v))
}

func hlNum(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

// hlStr makes a string safe as a hyprlang value: '#' starts a comment unless
// doubled, and a newline would end the line and let the rest be read as config.
func hlStr(s string) string {
	s = strings.NewReplacer("\r", " ", "\n", " ").Replace(s)
	return strings.ReplaceAll(strings.TrimSpace(s), "#", "##")
}

var hexColour = regexp.MustCompile(`^[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$`)

// hlRGB turns "#rrggbb" (or "rrggbb", or "#rrggbbaa") into Hyprland's rgb()/rgba()
// form. A value that is not a colour yields the fallback rather than a line the
// compositor cannot parse.
func hlRGB(hex, fallback string) string {
	h := strings.TrimPrefix(strings.TrimSpace(hex), "#")
	if !hexColour.MatchString(h) {
		h = strings.TrimPrefix(fallback, "#")
	}
	if len(h) == 8 {
		return "rgba(" + strings.ToLower(h) + ")"
	}
	return "rgb(" + strings.ToLower(h) + ")"
}

