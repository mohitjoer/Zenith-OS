package adopt

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// UndoScript generates the reversal of a plan.
//
// Two properties make it a script and not a function.
//
// It is a plain file, because the moment it is needed the user may have no
// working desktop to run a Go binary from. A machine that will not boot into its
// session is exactly when the undo has to work.
//
// It is written BEFORE the first write, so it exists even if adoption dies half
// way through. Generating it afterwards means the failure case with no way back
// is precisely the failure case where you need it most.
func UndoScript(plan Plan, state *State) string {
	var out strings.Builder

	out.WriteString(`#!/bin/sh
# Generated by zenith adopt. This reverses what adoption did.
#
# Written before the first change, so it exists even if adoption was
# interrupted. It is a plain file rather than a zenith subcommand because the
# moment it is needed there may be no working desktop to run one from.
#
# Read it before running it. Everything it removes, it removes because it was
# listed in the backup directory, and everything it restores, it restores from
# a copy it took first.
set -eu

`)
	out.WriteString(fmt.Sprintf("USER=%s\n", shellQuote(state.User.Name)))
	out.WriteString(fmt.Sprintf("HOME_DIR=%s\n", shellQuote(state.User.Home)))
	out.WriteString(fmt.Sprintf("BACKUP=%s\n\n", shellQuote(plan.BackupDir)))

	out.WriteString(`if [ "$(id -u)" -ne 0 ]; then
    echo "This script needs root." >&2
    exit 1
fi

# ---------------------------------------------------------------- root work
echo "==> restoring packages"
`)

	if len(state.Packages.Removed) == 0 {
		out.WriteString("echo \"  nothing was removed\"\n")
	} else {
		out.WriteString("for p in " + shellQuoteList(state.Packages.Removed) + "; do\n")
		out.WriteString("    [ -s \"$BACKUP/packages.removed\" ] && ")
		out.WriteString("grep -qx \"$p\" \"$BACKUP/packages.removed\" && ")
		out.WriteString("apt-get install -y \"$p\" || echo \"  could not reinstall $p\"\n")
		out.WriteString("done\n")
	}

	out.WriteString(`
# Finish any package transaction adoption interrupted. Adoption never writes
# dpkg's database directly, so there is nothing to restore here — only to
# complete.
dpkg --configure -a || true
apt-get -f install -y || true

echo "==> removing the registrations adoption materialized"
# The packaged content under /usr/share/zenith/ stays. Nothing there needs
# removing, and removing it would leave the package half-installed.
`)

	for _, registration := range state.Registrations {
		out.WriteString(fmt.Sprintf("rm -f %s\n", shellQuote(registration.Path)))
	}

	out.WriteString(`
glib-compile-schemas /usr/share/glib-2.0/schemas || true
systemctl --user daemon-reload 2>/dev/null || true

echo "==> restoring x-terminal-emulator"
if [ -s "$BACKUP/x-terminal-emulator.path" ]; then
    update-alternatives --set x-terminal-emulator \
        "$(cat "$BACKUP/x-terminal-emulator.path")" || \
        echo "  could not restore the terminal alternative"
fi

# -------------------------------------------------------------- user work
echo "==> restoring the portal preference"
`)
	if len(state.UserWrites) == 0 {
		out.WriteString("echo \"  nothing was written in the user tree\"\n")
	}
	for _, write := range state.UserWrites {
		if write.ArchivedTo == "" {
			continue
		}
		// ArchivedTo is the copy, Path is what it is copied to. Reading them
		// the wrong way round produces a script that copies a file onto itself
		// and restores nothing, which looks like it ran.
		out.WriteString(fmt.Sprintf(`if [ -f %s ]; then
    mkdir -p "$(dirname %s)"
    cp -a %s %s
    chown "$USER" %s
fi
`, shellQuote(write.ArchivedTo), shellQuote(write.Path),
			shellQuote(write.ArchivedTo), shellQuote(write.Path),
			shellQuote(write.Path)))
	}

	if state.Prune.Performed {
		out.WriteString(`
# The prune step is not reversed here. Removing GNOME took the desktop away, and
# putting it back is an apt-get install on the packages the backup lists,
# which is a decision and not an automatic one.
echo "==> GNOME was removed by the prune step"
if [ -s "$BACKUP/packages.purged" ]; then
    echo "    to put it back:"
    echo "      xargs -a \"$BACKUP/packages.purged\" apt-get install -y"
fi
`)
	}

	out.WriteString(`
echo
echo "Undo finished. Log out and back in to pick the session up at the login screen."
echo "The backup is at $BACKUP — delete it once you are satisfied."
`)

	return out.String()
}

// WriteUndoScript writes the generated script and makes it executable.
//
// 0755 rather than 0644 because the whole point is that the user can run it
// without reading the permissions out first, and a script that is not
// executable at the moment it is needed is a script that needs one more step
// during the worst possible time.
func WriteUndoScript(path string, plan Plan, state *State) error {
	if dir := filepath.Dir(path); dir != "" {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, []byte(UndoScript(plan, state)), 0o755)
}

// shellQuote makes one argument safe.
//
// Everything is quoted, always, with no exceptions for values that "obviously"
// need no quoting. A path with a space in a user's home directory is ordinary,
// not exotic, and a script that handles only the paths the developer tested is a
// script that fails on the user it was written for.
func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}

func shellQuoteList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, shellQuote(value))
	}
	return strings.Join(quoted, " ")
}
