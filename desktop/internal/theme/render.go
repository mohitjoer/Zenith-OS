package theme

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/BurntSushi/toml"
)

// Marker is the phrase every shipped template carries in its first lines. A file
// in somebody else's config directory is overwritten only while it still carries
// it, which is how a user's own file is told from one we wrote without keeping a
// ledger of what we wrote.
const Marker = "Rendered by zenith theme"

// Rendered is what became of one [templates.NAME] block.
type Rendered struct {
	Block, Dest, Status string
}

// Render runs a matugen-style config over a carrier, the colours the templates
// name: {"colors": {NAME: {"default": {"hex": ...}, "dark": ..., "light": ...}}}.
// Every block is attempted; a block that fails is reported and the rest still
// render, so one broken template does not freeze every other app on the last
// palette.
func Render(configPath string, carrier map[string]any) ([]Rendered, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return nil, err
	}
	var config struct {
		Templates map[string]struct {
			Input  string `toml:"input_path"`
			Output string `toml:"output_path"`
		} `toml:"templates"`
	}
	if _, err := toml.DecodeFile(configPath, &config); err != nil {
		return nil, err
	}

	names := make([]string, 0, len(config.Templates))
	for name := range config.Templates {
		names = append(names, name)
	}
	sort.Strings(names)

	var done []Rendered
	failed := 0
	for _, name := range names {
		block := config.Templates[name]
		r := Rendered{Block: name, Dest: expandHome(block.Output, home)}
		status, err := renderOne(home, expandHome(block.Input, home), r.Dest, carrier)
		if err != nil {
			status = "error: " + err.Error()
			failed++
		}
		r.Status = status
		done = append(done, r)
	}
	if failed > 0 {
		return done, fmt.Errorf("%d of %d templates failed", failed, len(names))
	}
	return done, nil
}

func renderOne(home, input, dest string, carrier map[string]any) (string, error) {
	// An app's own per-user directory, and nowhere else.
	if !within(dest, home) {
		return "", fmt.Errorf("%s is outside the home directory", dest)
	}

	template, err := os.ReadFile(input)
	if os.IsNotExist(err) {
		// Not materialised yet: the packaged copy is the same file.
		config := filepath.Join(home, ".config", "zenith")
		if within(input, config) {
			rel, _ := filepath.Rel(config, input)
			template, err = os.ReadFile(filepath.Join("/usr/share/zenith", rel))
		}
	}
	if err != nil {
		return "", err
	}
	text, err := expand(string(template), carrier)
	if err != nil {
		return "", err
	}

	if why := leaveAlone(home, dest); why != "" {
		return "left alone: " + why, nil
	}
	if old, err := os.ReadFile(dest); err == nil && string(old) == text {
		return "unchanged", nil
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return "", err
	}
	// Renamed into place: an app reading while we write never sees half a file.
	tmp := dest + ".tmp"
	if err := os.WriteFile(tmp, []byte(text), 0o644); err != nil {
		return "", err
	}
	if err := os.Rename(tmp, dest); err != nil {
		os.Remove(tmp)
		return "", err
	}
	return "wrote", nil
}

// leaveAlone says why dest must not be written, or "" when it may be.
//
// Zenith's own directories follow the overlay model: a user edit wins at the
// mirrored path. Anywhere else the file is somebody's unless it still carries
// the marker, and a symlink is never written through (it points at a file that
// is not ours, wherever it lives).
func leaveAlone(home, dest string) string {
	config := filepath.Join(home, ".config", "zenith")
	if within(dest, config) {
		rel, _ := filepath.Rel(config, dest)
		if _, err := os.Lstat(filepath.Join(config, "user_edits", rel)); err == nil {
			return "a user edit wins"
		}
		return ""
	}
	if within(dest, filepath.Join(home, ".cache", "zenith")) {
		return ""
	}

	info, err := os.Lstat(dest)
	if err != nil {
		return ""
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return "it is a symlink"
	}
	file, err := os.Open(dest)
	if err != nil {
		return err.Error()
	}
	defer file.Close()
	head := make([]byte, 512)
	n, _ := file.Read(head)
	if !bytes.Contains(head[:n], []byte(Marker)) {
		return "it was not generated by zenith theme"
	}
	return ""
}

var (
	exprRe    = regexp.MustCompile(`\{\{\s*(.*?)\s*\}\}`)
	replaceRe = regexp.MustCompile(`^replace:\s*"([^"]*)"\s*,\s*"([^"]*)"$`)
)

// expand fills the {{ colors.NAME.BUCKET.FIELD }} expressions of a template. The
// one filter the shipped templates use is `replace`. An expression that does not
// resolve fails the template instead of rendering an empty colour.
func expand(template string, carrier map[string]any) (string, error) {
	var failure error
	out := exprRe.ReplaceAllStringFunc(template, func(match string) string {
		parts := strings.Split(exprRe.FindStringSubmatch(match)[1], "|")
		value, err := lookup(carrier, strings.TrimSpace(parts[0]))
		for _, filter := range parts[1:] {
			if err != nil {
				break
			}
			if r := replaceRe.FindStringSubmatch(strings.TrimSpace(filter)); r != nil {
				value = strings.ReplaceAll(value, r[1], r[2])
			} else {
				err = fmt.Errorf("unknown filter %q", strings.TrimSpace(filter))
			}
		}
		if err != nil && failure == nil {
			failure = err
		}
		return value
	})
	return out, failure
}

func lookup(carrier map[string]any, path string) (string, error) {
	var node any = carrier
	for _, key := range strings.Split(path, ".") {
		branch, ok := node.(map[string]any)
		if !ok {
			return "", fmt.Errorf("%s: no such colour", path)
		}
		if node, ok = branch[key]; !ok {
			return "", fmt.Errorf("%s: no such colour", path)
		}
	}
	value, ok := node.(string)
	if !ok {
		return "", fmt.Errorf("%s: not a value", path)
	}
	return value, nil
}

func expandHome(path, home string) string {
	if rest, ok := strings.CutPrefix(path, "~/"); ok {
		return filepath.Join(home, rest)
	}
	return path
}

func within(path, dir string) bool {
	rel, err := filepath.Rel(dir, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, "../")
}
