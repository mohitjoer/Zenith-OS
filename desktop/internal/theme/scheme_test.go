// TestEverySchemeIsReadableAndReproducible is the contract the rest of the
// desktop leans on: whichever scheme the Hub picks and however high the contrast
// knob is, the same seed gives the same bytes and every text pair clears the
// floor, because a tone is L* and the tables only pair tones that are far apart.
func TestEverySchemeIsReadableAndReproducible(t *testing.T) {
	seed := Colour{0.26, 0.52, 0.96}
	for _, name := range SchemeNames() {
		for _, contrast := range []float64{0, 1} {
			opts := Options{Scheme: "scheme-" + name, Contrast: contrast}
			first, err := Generate(seed, opts)
			if err != nil {
				t.Fatal(err)
			}
			second, _ := Generate(seed, opts)
			a, _ := json.Marshal(first.Matugen(true))
			b, _ := json.Marshal(second.Matugen(true))
			if !bytes.Equal(a, b) {
				t.Errorf("%s: two runs gave different documents", name)
			}

			for _, dark := range []bool{true, false} {
				palette := map[string]Colour{}
				for key, hex := range ShellColors(first.Flat(dark)) {
					c, err := parseHex(hex)
					if err != nil {
						t.Fatalf("%s: %s = %q: %v", name, key, hex, err)
					}
					palette[key] = c
				}
				if problems := CheckRoles(palette); len(problems) != 0 {
					t.Errorf("%s contrast %v dark=%v: %v", name, contrast, dark, problems)
				}
			}
		}
	}
}

// TestMonochromeHasNoHueButError is the design-system rule for the default
// scheme: grey everywhere, red only where a role means error.
func TestMonochromeHasNoHueButError(t *testing.T) {
	s, err := Generate(Colour{0.9, 0.3, 0.1}, Options{})
	if err != nil {
		t.Fatal(err)
	}
	for _, mode := range []map[string]Colour{s.Dark, s.Light} {
		for name, c := range mode {
			hex := c.Hex()
			grey := hex[1:3] == hex[3:5] && hex[3:5] == hex[5:7]
			switch {
			case strings.Contains(name, "error"):
				if name == "error" && c.R <= c.G {
					t.Errorf("error %s is not red", hex)
				}
			case name == "source_color":
			case !grey:
				t.Errorf("%s = %s is not grey", name, hex)
			}
		}
	}
}

// TestRenderLeavesOtherPeoplesFilesAlone: a render may only replace what it
// wrote itself, and one bad template must not stop the others.
func TestRenderLeavesOtherPeoplesFilesAlone(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	put := func(rel, body string) string {
		p := filepath.Join(home, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	put("tpl/ok", "/* "+Marker+" */ {{ colors.primary.default.hex }} {{colors.primary.default.hex | replace: \"#\", \"\"}}")
	put("tpl/bad", "{{colors.nope.default.hex}}")

	blocks := map[string]string{
		"fresh": ".config/app/fresh.css", "theirs": ".config/app/theirs.css",
		"link": ".config/app/link.css", "edited": ".config/zenith/apps/edited",
		"ours": ".config/app/ours.css", "outside": "../escape.css",
	}
	var config strings.Builder
	for name, out := range blocks {
		config.WriteString("[templates." + name + "]\ninput_path = \"~/tpl/ok\"\noutput_path = \"~/" + out + "\"\n")
	}
	config.WriteString("[templates.broken]\ninput_path = \"~/tpl/bad\"\noutput_path = \"~/.config/app/broken.css\"\n")
	configPath := put("c.toml", config.String())

	put(".config/app/theirs.css", "mine")
	put(".config/app/ours.css", "/* "+Marker+" */ stale")
	put(".config/zenith/user_edits/apps/edited", "mine")
	target := put("elsewhere.css", "target")
	if err := os.Symlink(target, filepath.Join(home, ".config/app/link.css")); err != nil {
		t.Fatal(err)
	}

	carrier := map[string]any{"colors": map[string]any{"primary": map[string]any{"default": map[string]any{"hex": "#aabbcc"}}}}
	done, err := Render(configPath, carrier)
	if err == nil {
		t.Error("a template with an unknown colour did not fail the run")
	}

	want := map[string]string{
		"fresh": "wrote", "ours": "wrote",
		"theirs": "left alone: it was not generated by zenith theme",
		"link":   "left alone: it is a symlink",
		"edited": "left alone: a user edit wins",
	}
	for _, r := range done {
		switch {
		case r.Block == "broken" || r.Block == "outside":
			if !strings.HasPrefix(r.Status, "error:") {
				t.Errorf("%s: status %q, want an error", r.Block, r.Status)
			}
		case r.Status != want[r.Block]:
			t.Errorf("%s: status %q, want %q", r.Block, r.Status, want[r.Block])
		}
	}

	read := func(rel string) string {
		b, _ := os.ReadFile(filepath.Join(home, rel))
		return string(b)
	}
	if got := read(".config/app/fresh.css"); got != "/* "+Marker+" */ #aabbcc aabbcc" {
		t.Errorf("rendered %q", got)
	}
	if read(".config/app/theirs.css") != "mine" || read("elsewhere.css") != "target" ||
		read(".config/zenith/apps/edited") != "" {
		t.Error("a file that was not ours was written")
	}
}
