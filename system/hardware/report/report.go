// Input is everything a report is rendered from.
//
// It is passed in rather than read here, for the reason every reader in this
// subsystem takes a root: a report can be rendered from a captured machine, so
// the renderers are testable without a laptop.
type Input struct {
	DMI  probe.Fields
	PCI  []probe.Device
	USB  []probe.USBDevice
	ACPI probe.ACPIState
	EDID []probe.Panel

	// KernelFlavour is the running kernel's flavour — generic, hwe or oem —
	// never a patch version. The caller resolves it; this package refuses to
	// accept anything else.
	KernelFlavour string

	// RawDMI is the unclassified DMI dump, for the redaction sweep. The sweep
	// needs the raw values to compare against, and only the raw dump has them.
	RawDMI map[string]string

	// Host carries the machine's own identifying values so the sweep can catch
	// them: the sweep cannot recognise a hostname or a machine-id by shape.
	Host redact.Context

	// Salt produces the tokens that appear in the diagnostic shapes.
	Salt redact.Salt
}

// Format is an output shape.
type Format string

const (
	// FormatText is the diagnostic text, for pasting into a support form.
	FormatText Format = "text"
	// FormatJSON is the same content, machine-readable.
	FormatJSON Format = "json"
	// FormatProfile is the candidate profile YAML: schema-shaped, and carrying
	// no tokens at all.
	FormatProfile Format = "profile"
)

// Options selects an output shape.
type Options struct {
	Format Format
	// Deep adds the ACPI-derived facts. The deep probe writes to disk and is
	// CPU-bound, so it is opt-in even here.
	Deep bool
}

// Render produces the report, having swept it.
//
// The sweep is not optional and not advisory: nothing is returned unless the
// rendered bytes contain nothing they should not. This is the single place the
// contract is enforced, so a new renderer cannot skip it by being added in the
// wrong order.
func Render(input Input, opts Options) ([]byte, error) {
	if opts.Format == "" {
		opts.Format = FormatText
	}

	inferred := infer(input)

	var rendered []byte
	var err error

	switch opts.Format {
	case FormatText:
		rendered, err = renderText(input, inferred, opts)
	case FormatJSON:
		rendered, err = renderJSON(input, inferred, opts)
	case FormatProfile:
		rendered, err = renderProfile(input, inferred)
	default:
		return nil, errorf("report: unknown format %q", opts.Format)
	}
	if err != nil {
		return nil, err
	}

	if findings := redact.Verify(rendered, input.Host); len(findings) > 0 {
		return nil, errorf("%s", redact.Refusal(findings))
	}
	return rendered, nil
}

// renderProfile emits the candidate profile YAML.
//
// Three rules shape it, all of them from the profile schema:
//
//   - **No tokens at all.** A profile's match key needs none of the hashed
//     fields, so the committed artefact contains none. This shape is therefore
//     not merely redacted; it is a different, smaller document.
//   - **No kernel patch version.** The flavour only. A profile that pins
//     6.8.0-31-generic stops matching the next security update, and a candidate
//     carrying one teaches the contributor the wrong shape.
//   - **No firmware file, ever.** Firmware is named as packages, and only from
//     the reviewed set. Detection cannot resolve a blob to a package without
//     the firmware-set data file, so it names none and says so.
func renderProfile(input Input, inferred Inference) ([]byte, error) {
	w := newYAML()

	w.comment(0, "Candidate hardware profile — generated by `zenith hardware report`.")
	w.comment(0, "Review before opening a pull request. `verified:` is for a human on this")
	w.comment(0, "machine; detection cannot fill it in. Fields that would identify this")
	w.comment(0, "machine have been removed, not redacted.")

	w.raw(0, "version", "1")

	// GPL-3.0 is the value for a profile that only names base-layer packages,
	// because a package name is not a licence grant and the blob's own copyright
	// file governs. A profile carrying something a third party wrote records that
	// work's terms here instead — so the comment has to travel with the value,
	// or a contributor adds a vendor patch and leaves this saying GPL-3.0.
	w.scalar(0, "license", "GPL-3.0")
	w.comment(0, "If this profile names a vendor patch, quotes a licence or carries")
	w.comment(0, "firmware terms, record that work's terms here instead. See LICENSING.md.")

	id, err := profileID(input.DMI)
	if err != nil {
		return nil, err
	}
	w.scalar(0, "id", id)

	// A freshly generated profile has been through no checklist. It is tier 2 by
	// construction, and saying so is more useful than leaving a maintainer to
	// guess what a missing tier means.
	w.raw(0, "tier", "2")

	w.key(0, "match")
	w.matchFields(input.DMI)

	// Only ever a flavour. A profile pinning a patch version stops matching at
	// the next security update.
	//
	// When detection could not determine the flavour, the profile says so rather
	// than naming one. Defaulting to "generic" here would be a silent claim: a
	// reader cannot tell it apart from a machine that genuinely reports generic,
	// and the wrong kernel flavour installs a kernel that does not drive the
	// machine's hardware.
	if inferred.KernelFlavour != "" {
		w.scalar(0, "kernel", inferred.KernelFlavour)
	} else {
		w.comment(0, "kernel: detection could not determine this machine's kernel")
		w.comment(0, "flavour. Choose one of generic, hwe or oem and delete this")
		w.comment(0, "comment — a profile must name a flavour to install a kernel.")
	}

	w.blank()
	w.key(0, "gpu")
	if inferred.GPUDiscrete != "" {
		w.scalar(1, "discrete", inferred.GPUDiscrete)
	}
	w.scalar(1, "integrated", orDefault(inferred.GPUIntegrated, "auto"))
	if inferred.HybridMux {
		w.comment(1, "Two display devices. The mux mechanism is a vendor tool and")
		w.comment(1, "cannot be derived here; a human must name it.")
		w.key(1, "hybrid_mux")
		w.raw(2, "enabled", "true")
	} else {
		w.key(1, "hybrid_mux")
		w.raw(2, "enabled", "false")
	}

	w.blank()
	w.key(0, "network")
	w.key(1, "wifi")
	if len(inferred.WifiDrivers) == 0 {
		w.comment(2, "No wireless device found.")
	} else {
		for _, driver := range inferred.WifiDrivers {
			w.scalar(2, "- driver", driver)
			w.emptyList(3, "firmware")
		}
	}

	w.blank()
	w.key(0, "audio")
	w.scalar(1, "codec", orDefault(inferred.AudioCodec, "hda"))
	w.emptyList(1, "quirks")

	w.blank()
	w.key(0, "storage")
	w.emptyList(1, "quirks")

	w.blank()
	w.key(0, "firmware")
	w.comment(1, "Detection does not name firmware packages: resolving a blob to the")
	w.comment(1, "package that ships it needs the firmware-set data file, and a wrong")
	w.comment(1, "name here installs nothing. A human fills this in from the device.")
	w.emptyList(1, "packages")
	if inferred.Microcode != "" {
		w.list(1, "microcode", []string{inferred.Microcode})
	} else {
		w.comment(1, "No host bridge found, so the microcode package is not named.")
		w.emptyList(1, "microcode")
	}

	w.blank()
	w.key(0, "verified")
	for _, item := range []string{
		"suspend_resume", "external_display", "bluetooth", "fingerprint",
	} {
		w.scalar(1, item, "untested")
	}
	w.emptyList(1, "known_issues")

	w.blank()
	w.folded(0, "notes", "Replace with anything a future maintainer needs and cannot "+
		"derive from the machine. Write what you tried, not just what you concluded.")

	return w.Bytes(), nil
}

// matchFields writes the match block.
//
// The order is the design record's order, and the values are written through the
// quoting helper because `1.0` unquoted is a float that will not compare equal
// to the string the machine reports.
func (w *yamlWriter) matchFields(fields probe.Fields) {
	w.matchScalar("sys_vendor", fields.SysVendor)
	w.matchScalar("product_name", fields.ProductName)
	w.matchScalar("product_version", fields.ProductVersion)
	w.matchScalar("product_family", fields.ProductFamily)
	w.matchScalar("product_sku", fields.ProductSKU)
	w.matchScalar("board_vendor", fields.BoardVendor)
	w.matchScalar("board_name", fields.BoardName)
	w.matchScalar("board_version", fields.BoardVersion)
	w.matchScalar("chassis_type", fields.ChassisType)
	w.matchScalar("bios_vendor", fields.BIOSVendor)
	w.matchScalar("bios_version", fields.BIOSVersion)

	// A comparator rather than an equality: a profile pinning an exact firmware
	// date stops matching the day the vendor ships a new one.
	if fields.BIOSDate != "" {
		w.comment(1, "A firmware-date comparator, not an equality: an exact date")
		w.comment(1, "stops matching at the next vendor update.")
		w.scalar(1, "bios_date", ">=2020-01-01")
	}
}

// matchScalar writes one match field, omitting an absent value rather than
// emitting an empty one. An absent field is unconstrained; an empty field is a
// value the machine must have.
func (w *yamlWriter) matchScalar(name, value string) {
	if value == "" {
		return
	}
	w.scalar(1, name, value)
}

// profileID derives a filename-safe identifier from the machine's identity.
//
// The value is a suggestion. It is derived only from strings the profile will
// carry anyway, so it cannot identify anything the match key does not, and a
// human is expected to change it — two machines of one model in different
// configurations need different ids, and detection cannot see the difference.
func profileID(fields probe.Fields) (string, error) {
	parts := []string{}

	appendPart := func(value string) {
		if value != "" {
			parts = append(parts, value)
		}
	}

	// Vendor first, then the most identifying model string available.
	if fields.SysVendor != "" && !isPlaceholder(fields.SysVendor) {
		appendPart(fields.SysVendor)
	} else {
		// A vendor of "To Be Filled By O.E.M." is not a vendor.
		appendPart("unknown-vendor")
	}

	model := firstNonEmpty(fields.ProductName, fields.ProductFamily, fields.BoardName)
	if model == "" {
		return "", errorf("report: no identity to derive a profile id from; " +
			"the machine has neither DMI nor a device tree")
	}
	if isPlaceholder(model) {
		model = fields.BoardName
	}
	appendPart(model)

	// product_sku is the field that distinguishes two configurations of one
	// model, which is exactly what an id needs.
	if fields.ProductSKU != "" && !isPlaceholder(fields.ProductSKU) {
		appendPart(fields.ProductSKU)
	}

	return slug(strings.Join(parts, "-")), nil
}

// isPlaceholder reports whether a string is firmware filler rather than an
// identity. A VM whose DMI says "To Be Filled By O.E.M." in every field is the
// common case, and a profile derived from it would be a name for nothing.
func isPlaceholder(value string) bool {
	normalised := strings.ToLower(strings.TrimSpace(value))
	return strings.Contains(normalised, "to be filled by") ||
		strings.Contains(normalised, "default string") ||
		strings.Contains(normalised, "system product name") ||
		normalised == "unknown" ||
		normalised == "none"
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}

func orDefault(value, fallback string) string {
	if value == "" {
		return fallback
	}
	return value
}

// slug reduces a string to the lowercase-hyphenated form the profile schema
// requires of an id.
func slug(value string) string {
	var b strings.Builder
	previousHyphen := false
	for _, r := range strings.ToLower(value) {
		switch {
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9'):
			b.WriteRune(r)
			previousHyphen = false
		default:
			if !previousHyphen && b.Len() > 0 {
				b.WriteByte('-')
				previousHyphen = true
			}
		}
	}
	return strings.Trim(b.String(), "-")
}

// renderText emits the human diagnostic, for pasting into the hardware support
// form. Serials appear as tokens only.
func renderText(input Input, inferred Inference, opts Options) ([]byte, error) {
	var b bytes.Buffer

	b.WriteString("Zenith hardware report\n")
	b.WriteString("=======================\n\n")

	fmt.Fprintf(&b, "Kernel flavour: %s\n\n", orDefault(inferred.KernelFlavour, "unknown"))

	b.WriteString("Machine\n-------\n")
	writeField(&b, "sys_vendor", input.DMI.SysVendor)
	writeField(&b, "product_name", input.DMI.ProductName)
	writeField(&b, "product_version", input.DMI.ProductVersion)
	writeField(&b, "product_family", input.DMI.ProductFamily)
	writeField(&b, "product_sku", input.DMI.ProductSKU)
	writeField(&b, "board_vendor", input.DMI.BoardVendor)
	writeField(&b, "board_name", input.DMI.BoardName)
	writeField(&b, "board_version", input.DMI.BoardVersion)
	writeField(&b, "chassis_type", input.DMI.ChassisType)
	writeField(&b, "bios_vendor", input.DMI.BIOSVendor)
	writeField(&b, "bios_version", input.DMI.BIOSVersion)
	writeField(&b, "bios_date", input.DMI.BIOSDate)
	// The UUID appears as a keyed token, never as itself.
	if input.DMI.ProductUUIDHash != "" {
		fmt.Fprintf(&b, "product_uuid token: %s\n",
			redact.Token(input.Salt, "product_uuid", input.DMI.ProductUUIDHash))
	}

	b.WriteString("\nDevices\n-------\n")
	for _, device := range input.PCI {
		fmt.Fprintf(&b, "PCI %s  %s:%s  class %s\n",
			device.Address, device.Vendor, device.Device, device.Class)
		fmt.Fprintf(&b, "    driver: %s\n", orDefault(device.Driver, "none bound"))
		if len(device.CandidateModules) > 0 {
			fmt.Fprintf(&b, "    candidates: %s\n", strings.Join(device.CandidateModules, ", "))
		}
		if device.BootVGA {
			b.WriteString("    boot_vga: yes\n")
		}
		if device.IsVirtualFunction {
			b.WriteString("    virtual function: yes\n")
		}
	}
	for _, device := range input.USB {
		fmt.Fprintf(&b, "USB %s  %s:%s  %s\n",
			device.Name, device.IDVendor, device.IDProduct,
			strings.TrimSpace(device.Manufacturer+" "+device.Product))
	}

	b.WriteString("\nPanels\n------\n")
	for _, panel := range input.EDID {
		if !panel.Present {
			fmt.Fprintf(&b, "%s: not connected\n", panel.Connector)
			continue
		}
		fmt.Fprintf(&b, "%s: %s %s  %dx%d@%.2fHz\n",
			panel.Connector, panel.Manufacturer, panel.MonitorName,
			panel.Width, panel.Height, panel.RefreshHz)
		if panel.Internal {
			fmt.Fprintf(&b, "    internal (inferred from connector %s)\n",
				panel.InternalEvidence)
		}
	}

	b.WriteString("\nPlatform\n--------\n")
	fmt.Fprintf(&b, "ACPI present: %t\n", input.ACPI.Present)
	fmt.Fprintf(&b, "sleep mask: %s\n", orDefault(input.ACPI.MemSleep, "unknown"))
	fmt.Fprintf(&b, "default sleep: %s\n", orDefault(input.ACPI.DefaultMemSleep, "unknown"))
	fmt.Fprintf(&b, "platform profile: %s\n",
		orDefault(input.ACPI.PlatformProfile, "unknown"))
	fmt.Fprintf(&b, "backlight: %t\n", input.ACPI.BacklightGraphics)
	if opts.Deep {
		// The table *names*, never a table. A dump embeds identifiers as _DSM
		// GUIDs and as strings in arguments.
		fmt.Fprintf(&b, "ACPI tables: %s\n", strings.Join(input.ACPI.Tables, ", "))
	}

	if problems := inferred.validate(); len(problems) > 0 {
		b.WriteString("\nUnresolved\n----------\n")
		for _, problem := range problems {
			fmt.Fprintf(&b, "- %s\n", problem)
		}
	}

	return b.Bytes(), nil
}

func writeField(b *bytes.Buffer, name, value string) {
	if value == "" {
		return
	}
	fmt.Fprintf(b, "%-16s %s\n", name+":", value)
}

// jsonReport is the machine-readable shape. It is a struct rather than a map so
// that key order is stable and a golden test is meaningful.
type jsonReport struct {
	KernelFlavour string       `json:"kernel_flavour"`
	Machine       jsonMachine  `json:"machine"`
	Devices       []jsonDevice `json:"devices"`
	Panels        []jsonPanel  `json:"panels"`
	Platform      jsonPlatform `json:"platform"`
	Inferred      jsonInferred `json:"inferred"`
	Unresolved    []string     `json:"unresolved,omitempty"`
	Notes         jsonNotes    `json:"notes"`
}

type jsonNotes struct {
	SerialsAreTokens  bool `json:"serials_are_tokens"`
	TokensRotate      bool `json:"tokens_rotate_with_salt"`
	TokensIdentify    bool `json:"tokens_identify_the_machine"`
	DetectedByMachine bool `json:"this_does_not_say_the_machine_works"`
}

type jsonMachine struct {
	SysVendor        string `json:"sys_vendor,omitempty"`
	ProductName      string `json:"product_name,omitempty"`
	ProductVersion   string `json:"product_version,omitempty"`
	ProductFamily    string `json:"product_family,omitempty"`
	ProductSKU       string `json:"product_sku,omitempty"`
	BoardVendor      string `json:"board_vendor,omitempty"`
	BoardName        string `json:"board_name,omitempty"`
	BoardVersion     string `json:"board_version,omitempty"`
	ChassisType      string `json:"chassis_type,omitempty"`
	BIOSVendor       string `json:"bios_vendor,omitempty"`
	BIOSVersion      string `json:"bios_version,omitempty"`
	BIOSDate         string `json:"bios_date,omitempty"`
	ProductUUIDToken string `json:"product_uuid_token,omitempty"`
}

type jsonDevice struct {
	Kind             string   `json:"kind"`
	Address          string   `json:"address"`
	Vendor           string   `json:"vendor,omitempty"`
	Device           string   `json:"device,omitempty"`
	Class            string   `json:"class,omitempty"`
	Driver           string   `json:"driver,omitempty"`
	CandidateModules []string `json:"candidate_modules,omitempty"`
	BootVGA          bool     `json:"boot_vga,omitempty"`
	VirtualFunction  bool     `json:"virtual_function,omitempty"`
}

type jsonPanel struct {
	Connector        string  `json:"connector"`
	Present          bool    `json:"present"`
	Manufacturer     string  `json:"manufacturer,omitempty"`
	MonitorName      string  `json:"monitor_name,omitempty"`
	ProductCode      string  `json:"product_code,omitempty"`
	Width            int     `json:"width,omitempty"`
	Height           int     `json:"height,omitempty"`
	RefreshHz        float64 `json:"refresh_hz,omitempty"`
	Internal         bool    `json:"internal"`
	InternalEvidence string  `json:"internal_evidence,omitempty"`
}

type jsonPlatform struct {
	ACPI            bool     `json:"acpi"`
	MemSleep        string   `json:"mem_sleep,omitempty"`
	DefaultMemSleep string   `json:"default_mem_sleep,omitempty"`
	PlatformProfile string   `json:"platform_profile,omitempty"`
	Backlight       bool     `json:"backlight"`
	ACIPTables      []string `json:"acpi_tables,omitempty"`
}

type jsonInferred struct {
	GPUIntegrated string   `json:"gpu_integrated,omitempty"`
	GPUDiscrete   string   `json:"gpu_discrete,omitempty"`
	HybridMux     bool     `json:"hybrid_mux"`
	WifiDrivers   []string `json:"wifi_drivers,omitempty"`
	AudioCodec    string   `json:"audio_codec,omitempty"`
	Microcode     string   `json:"microcode,omitempty"`
	InternalPanel string   `json:"internal_panel,omitempty"`
}

func renderJSON(input Input, inferred Inference, opts Options) ([]byte, error) {
	doc := jsonReport{
		KernelFlavour: inferred.KernelFlavour,
		Machine: jsonMachine{
			SysVendor:        input.DMI.SysVendor,
			ProductName:      input.DMI.ProductName,
			ProductVersion:   input.DMI.ProductVersion,
			ProductFamily:    input.DMI.ProductFamily,
			ProductSKU:       input.DMI.ProductSKU,
			BoardVendor:      input.DMI.BoardVendor,
			BoardName:        input.DMI.BoardName,
			BoardVersion:     input.DMI.BoardVersion,
			ChassisType:      input.DMI.ChassisType,
			BIOSVendor:       input.DMI.BIOSVendor,
			BIOSVersion:      input.DMI.BIOSVersion,
			BIOSDate:         input.DMI.BIOSDate,
			ProductUUIDToken: redact.Token(input.Salt, "product_uuid", input.DMI.ProductUUIDHash),
		},
		Notes: jsonNotes{
			SerialsAreTokens:  true,
			TokensRotate:      true,
			TokensIdentify:    false,
			DetectedByMachine: false,
		},
	}

	for _, device := range input.PCI {
		doc.Devices = append(doc.Devices, jsonDevice{
			Kind:             deviceKind(device),
			Address:          device.Address,
			Vendor:           device.Vendor,
			Device:           device.Device,
			Class:            device.Class,
			Driver:           device.Driver,
			CandidateModules: device.CandidateModules,
			BootVGA:          device.BootVGA,
			VirtualFunction:  device.IsVirtualFunction,
		})
	}
	for _, device := range input.USB {
		doc.Devices = append(doc.Devices, jsonDevice{
			Kind:    "usb",
			Address: device.Name,
			Vendor:  device.IDVendor,
			Device:  device.IDProduct,
			Driver:  device.Driver,
		})
	}

	for _, panel := range input.EDID {
		doc.Panels = append(doc.Panels, jsonPanel{
			Connector:        panel.Connector,
			Present:          panel.Present,
			Manufacturer:     panel.Manufacturer,
			MonitorName:      panel.MonitorName,
			ProductCode:      panel.ProductCode,
			Width:            panel.Width,
			Height:           panel.Height,
			RefreshHz:        panel.RefreshHz,
			Internal:         panel.Internal,
			InternalEvidence: panel.InternalEvidence,
		})
	}

	doc.Platform = jsonPlatform{
		ACPI:            input.ACPI.Present,
		MemSleep:        input.ACPI.MemSleep,
		DefaultMemSleep: input.ACPI.DefaultMemSleep,
		PlatformProfile: input.ACPI.PlatformProfile,
		Backlight:       input.ACPI.BacklightGraphics,
	}
	if opts.Deep {
		doc.Platform.ACIPTables = input.ACPI.Tables
	}

	doc.Inferred = jsonInferred{
		GPUIntegrated: inferred.GPUIntegrated,
		GPUDiscrete:   inferred.GPUDiscrete,
		HybridMux:     inferred.HybridMux,
		WifiDrivers:   inferred.WifiDrivers,
		AudioCodec:    inferred.AudioCodec,
		Microcode:     inferred.Microcode,
		InternalPanel: inferred.InternalPanel,
	}

	for _, problem := range inferred.validate() {
		doc.Unresolved = append(doc.Unresolved, problem.Error())
	}

	// Indented output: a report gets read by a human in a pull request as often
	// as by a machine, and one-line-per-key JSON is unreadable.
	encoded, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, errorf("report: encoding json: %w", err)
	}
	return append(encoded, '\n'), nil
}

func deviceKind(device probe.Device) string {
	switch {
	case device.IsDisplay():
		return "display"
	case device.IsWireless():
		return "wireless"
	case device.IsNetwork():
		return "network"
	case device.IsAudio():
		return "audio"
	case device.IsStorage():
		return "storage"
	case device.IsUSBHost():
		return "usb-host"
	case isHostBridge(device.Class):
		return "host-bridge"
	}
	return "other"
}

// RawPathRefusesUnderCI reports whether an unredacted dump may be written.
//
// --raw writes a file containing serials. It refuses outright when CI is set,
// so a pipeline cannot produce a file intended for humans to keep local and then
// attach it to something.
//
// The environment is passed in rather than read from os.Getenv, because this is
// a decision the caller makes at startup and a function that reaches for the
// environment is a function a test cannot drive.
func RawPathRefusesUnderCI(environment string) bool {
	return environment != ""
}

// RawPathWarning is the message --raw prints alongside its path.
const RawPathWarning = "This file contains serials and asset identifiers. " +
	"Do not attach it to an issue, a pull request or anything else that " +
	"leaves this machine."
